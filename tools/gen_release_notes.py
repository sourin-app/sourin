#
# ★★ 2026-10-19（批末复核查出并修）：原来**漏了中文「新增」「功能」「回退」**
# ```text
# 实测（review 报告）：v1.0.0..v1.3.0 四个区间，`### 新增` 一次都没出现。
# 原因：USER_FACING 只有 `feat`（英文）没有 `新增`（中文），
