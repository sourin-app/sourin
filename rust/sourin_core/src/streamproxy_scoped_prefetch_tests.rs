//! Scoped large-media regression through actual split-Range HTTP requests.
//! Loopback-only fixture; instance state only, no environment/account access.
use super::*;
use crate::hls_query_policy::ScopedHlsQueryPolicy;
use crate::proxy::ProxyStore;
use axum::http::Request;

const QUERY: &str = "pid=fixture&sign=issued%2fKeep+Raw";
const TOTAL: u64 = PREFETCH_WINDOW as u64 + 97;
const KEYS: &[&str] = &["pid", "sign"];

#[derive(Clone, Debug)]
struct Hit { path: String, query: String, range: Option<String>, marker: Option<String> }

#[derive(Clone)]
struct Endpoint { hits:Arc<Mutex<Vec<Hit>>>, foreign:Option<String> }

async fn endpoint(request:Request<Body>, State(endpoint):State<Endpoint>) -> Response {
    let range = request.headers().get(header::RANGE).and_then(|value| value.to_str().ok()).map(str::to_owned);
    let query = request.uri().query().unwrap_or("").to_string();
    endpoint.hits.lock().unwrap().push(Hit {
        path:request.uri().path().into(), query:query.clone(), range:range.clone(),
        marker:request.headers().get("x-media-context").and_then(|value| value.to_str().ok()).map(str::to_owned),
    });
    if request.uri().path().ends_with("root.m3u8") {
        return Response::builder().header(header::CONTENT_TYPE,"application/vnd.apple.mpegurl")
            .body(Body::from("#EXTM3U\n#EXTINF:10,\nlarge.mp4\n#EXT-X-ENDLIST\n")).unwrap();
    }
    let (start,end) = match range.as_deref() {
        Some(range) => {
            let (start,end) = range.strip_prefix("bytes=").unwrap().split_once('-').unwrap();
            (start.parse::<u64>().unwrap(), if end.is_empty() {TOTAL-1} else {end.parse::<u64>().unwrap().min(TOTAL-1)})
        }
        None => (0,TOTAL-1),
    };
    // The original media GET is an open-ended Range. Only the finite Range
    // requests generated by actual prefetch get a foreign redirect. A test
    // redirecting the initial request would miss the losing-client branch.
    let finite_range = range.as_deref().is_some_and(|range| !range.ends_with('-'));
    if let Some(foreign) = endpoint.foreign.as_ref().filter(|_| finite_range) {
        let location = format!("{foreign}/data.mp4?{query}");
        return Response::builder().status(StatusCode::FOUND).header(header::LOCATION,location)
            .body(Body::empty()).unwrap();
    }
    let data:Vec<_> = (start..=end).map(|index| (index % 251) as u8).collect();
    Response::builder().status(if range.is_some() {StatusCode::PARTIAL_CONTENT} else {StatusCode::OK})
        .header(header::CONTENT_TYPE,"video/mp4")
        .header(header::ACCEPT_RANGES,"bytes")
        .header(header::CONTENT_LENGTH,data.len())
        .header(header::CONTENT_RANGE,format!("bytes {start}-{end}/{TOTAL}"))
        .body(Body::from(data)).unwrap()
}

async fn serve(foreign:Option<String>) -> (String,Endpoint) {
    let state = Endpoint { hits:Arc::new(Mutex::new(Vec::new())),foreign };
    let router = Router::new().fallback(|State(state):State<Endpoint>, request:Request<Body>| async move {
        endpoint(request,State(state)).await
    }).with_state(state.clone());
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let base = format!("http://{}",listener.local_addr().unwrap());
    tokio::spawn(async move {axum::serve(listener,router).await.unwrap();});
    (base,state)
}

async fn fetch_case(scoped:bool) -> (Vec<Hit>,Vec<Hit>) {
    let (foreign,trap) = serve(None).await;
    let (origin,source) = serve(Some(foreign)).await;
    let stream = Arc::new(StreamProxy::with_proxy_store(Arc::new(ProxyStore::new())));
    // Deterministic instance-local switch; no global env mutation.
    stream.set_prefetch_disabled(false);
    let root = format!("{origin}/root.m3u8?{QUERY}");
    let headers = vec![("X-Media-Context".into(),"issued-fixture-context".into())];
    let local = if scoped {
        let policy = ScopedHlsQueryPolicy::new(&root,KEYS).unwrap();
        maybe_proxy_with_policy(&stream,&root,&headers,false,Some(&policy)).await.unwrap().unwrap()
    } else {
        maybe_proxy(&stream,&root,&headers,true).await.unwrap().unwrap()
    };
    let client = reqwest::Client::builder().no_proxy().timeout(std::time::Duration::from_secs(5)).build().unwrap();
    let playlist = client.get(local).send().await.unwrap().text().await.unwrap();
    let media = playlist.lines().find(|line| !line.is_empty() && !line.starts_with('#')).unwrap();
    let response = client.get(media).header(header::RANGE,"bytes=0-").send().await.unwrap();
    assert_eq!(response.status(),StatusCode::PARTIAL_CONTENT);
    let bytes = response.bytes().await.unwrap();
    let expected:Vec<_> = (0..TOTAL).map(|index| (index % 251) as u8).collect();
    assert_eq!(&bytes[..],&expected,"the same large Range resource must retain exact byte delivery");
    // Entire response drains the finite set of first+second-window requests;
    // there is no timing sleep and no URL/header value is logged externally.
    let source_hits = source.hits.lock().unwrap().clone();
    let trap_hits = trap.hits.lock().unwrap().clone();
    (source_hits,trap_hits)
}

#[tokio::test]
async fn scoped_prefetch_large_media_keeps_origin_boundary_after_initial_headers() {
    let (source,foreign) = fetch_case(true).await;
    assert!(source.iter().any(|hit| hit.path=="/large.mp4" && hit.range.as_deref()==Some("bytes=0-")
        && hit.query==QUERY && hit.marker.as_deref()==Some("issued-fixture-context")),
        "positive control must observe the actual scoped large media open and inherited issued query");
    assert!(foreign.is_empty(),
        "source-scoped Range prefetch must not disclose issued query or registered context to a foreign redirect");
}

#[tokio::test]
async fn scoped_prefetch_control_unscoped_large_media_exercises_finite_range_redirects() {
    let (source,foreign) = fetch_case(false).await;
    assert!(source.iter().filter(|hit| hit.path=="/large.mp4" && hit.range.as_deref().is_some_and(|range| !range.ends_with('-'))).count()>=4,
        "the exact large resource must actually exercise the generic split-Range branch");
    assert!(!foreign.is_empty(),"the unrelated source control retains ordinary redirect behavior");
    assert!(foreign.iter().all(|hit| hit.query.is_empty()),"generic HLS must not inherit the scoped source query");
}
