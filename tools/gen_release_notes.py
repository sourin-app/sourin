def scrub_for_users(body: str) -> str:
    """把一条提交标题清洗成**用户能读懂**的句子；读不通就返回空串（调用方丢弃）"""
    # ★★★ 2026-10-21（rc3 后重排）：**正向判据前置到第一步**。
    #   原文就不含任何「用户可感知面」⇒ 它是内部改动，后面的清理只是给废话化妆。
    #   （为什么必须前置而不是只在末尾做：末尾那一步会被前面的"结构清理"喂进
    #    更长的串，判断面更宽；前置是**入口闸门**，最便宜的否掉。）
    if not _has_user_surface(body):
        return ""

    # ① 内部标识：工单号 / 探针名 / 文件名 / 符号名
    s = _strip_internal_ids(body)

    for pat, rep in _SCRUB_RULES:
        s = re.sub(pat, rep, s)

    # ★★ 2026-10-19（复查后收紧）：开发用语**从正文里删掉**，而不是整条丢弃。
    #   实测原做法误伤 11 条真修复（见 _DROP_WORDS 的注释）。
    for w in _DROP_WORDS:
        s = re.sub(re.escape(w), "", s, flags=re.IGNORECASE)

    # ② 内部工程词：**按段**删。整条都删光 ⇒ 丢（返回空串）。
    #   ★ 为什么不整条丢：见 _drop_internal_segments 上方的 ★（误伤 11 条的教训）
    s = _drop_internal_segments(s)
    if not s:
        return ""

    # ②b 括号旁注里含实现词 ⇒ 只删旁注，保留主干（见 _strip_impl_asides 的 ★）
    s = _strip_impl_asides(s)
