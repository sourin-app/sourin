    #     因为它们的共性是「主语被删后整句没有第二句可救」，按段删救不回来。
    low0 = s.lower()
    if any(w.lower() in low0 for w in _DROP_WHOLE_IF_CONTAINS):
        return ""
    if any(w in low0 for w in _SITE_NAMES):
        return ""

