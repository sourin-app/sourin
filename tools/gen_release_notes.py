def run_selftest() -> int:
    """跑冻结样例；全过打印一行汇总，失败逐条打印差异并返回 1"""
    # ★ Windows 控制台是 GBK，直接打中文/⇒/— 会 UnicodeEncodeError。
    #   这里强制 UTF-8：换台机器（CI 的 ubuntu）行为不变，本机也不会崩。
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
        except Exception:  # pragma: no cover —— 老 Python / 被重定向的流
            pass

    fails = 0
    kept = 0
    for title, want_label, want_body in _SELFTEST_CASES:
        got = classify(title)
        if want_label is None:
            ok = got is None
        else:
            ok = got is not None and got == (want_label, want_body)
        if got is not None:
            kept += 1
        if not ok:
            fails += 1
            sys.stderr.write(
                "[selftest] FAIL %s\n  期望: %r / %r\n  实际: %r\n"
                % (title, want_label, want_body, got)
            )
    total = len(_SELFTEST_CASES)
    if fails:
        sys.stderr.write("[selftest] %d/%d 条失败\n" % (fails, total))
        return 1
    print("[selftest] ok: %d 条用例全部通过（保留 %d / 丢弃 %d）"
          % (total, kept, total - kept))
    return 0


