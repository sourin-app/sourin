_ASCII_WORD_RE = re.compile(r"[A-Za-z]{3,}")
_PAREN_GROUP_RE = re.compile(r"[（(][^（()）]*[)）]")

# ── ⑥b 「内部基建自述」判据（2026-10-21，Lead 逐行读出来的一条）─────────
#
# ★★ 反面样本：`语义色层（玻璃化的地基）`
#    它**自己承认了**自己是地基而不是成品：括号里那句「玻璃化的地基」
#    不是补充说明，而是"这条改动本身用户还看不见"的自我招供。
#
# ★ 为什么不能只写死这个字符串：真正要拦的是一整类"基建自述"——
#   任何一条把括号旁注写成「X 的地基 / Y 的第一步 / 的前置 / 准备工作 / 铺垫」
#   的条目，都是在说"我在为后面铺路"。这类改动对用户的价值**由后面的成品兑现**，
#   成品自己会单独出现在同一版说明里（实测：同一个 M2 批次里，
#   `弹幕设置面板玻璃化`/`弹幕发送栏玻璃化`/`追更页玻璃化` 都独立成条）。
#   留着地基那条，用户只会问「语义色层是什么」。
#
# ★ 形态而不是黑名单：**旁注自述基建 ⇒ 先删旁注；删完主干仍命中用户面才留**。
#   于是「追更页玻璃化（M2 第一步）—— 进度条换成玻璃件」照样活（追更页是界面物件），
#   而「语义色层（玻璃化的地基）」只剩「语义色层」，命中不了白名单 ⇒ 整条丢。
#   这一步复用 `_strip_impl_asides` 的"删旁注留主干"，判据不另立一套。
#   加词标准沿用白名单那条：用户能不能在界面/功能上指出来。
_FOUNDATION_WORDS = (
    "地基", "底座", "底板", "骨架", "打底", "基础层", "基础设施",
    "前置", "准备工作", "铺垫", "铺路", "第一步", "第一步的",
    "是后面的", "为后面", "为后续", "为之后", "将来", "后续接入",
)


def _ascii_word_allowed(w: str) -> bool:
    w = w.lower()
    return w in _FINAL_KEEP_ASCII or w in _MEDIA_FORMAT_TOKENS


def _strip_impl_asides(s: str) -> str:
    """删掉"括号旁注里含实现词 / 自述基建"的旁注（整段旁注不要），句子主干保留

    ★ 实测样本：`弹幕设置面板玻璃化（AppDialogShell 加可选 glass 档）`
      —— 整条被 ④ 丢掉，但**前半句是用户看得见的改动**（设置面板变玻璃）。
      旁注是"怎么做的"，可以整体不要；主干必须留。
    ★ 实测样本：`语义色层（玻璃化的地基）`
      —— 旁注自述"我是地基" ⇒ 删旁注 ⇒ 主干「语义色层」命中不了用户面 ⇒ 整条丢
      （丢在 `scrub_for_users` 的出口闸门，不在这个函数里）。
    """
    def _repl(m: re.Match[str]) -> str:
        inner = m.group(0)[1:-1]
        # ★ ⑥b：旁注自述"这是地基/第一步/前置" ⇒ 整段旁注不要
        if any(w in inner for w in _FOUNDATION_WORDS):
            return ""
        if any(not _ascii_word_allowed(w) for w in _ASCII_WORD_RE.findall(inner)):
            return ""
        # ★ 旁注**尾巴上有空白** ⇒ 说明末尾那个词被符号剥离吃掉了
        #   （「（自建容器 + 原生 TextField）」→「（自建容器 + 原生 ）」），
        #   旁注此时已经不成立 ⇒ 整段旁注一起删。
        if inner != inner.rstrip():
            return ""
        return m.group(0)

    return _PAREN_GROUP_RE.sub(_repl, s)


# ── ⑦ 排版统一（中文与括号 / 破折号）────────────────────────────────
#
# ★ 2026-10-21（Lead 反馈）：生成的句子单个看都对，连起来看**排布不统一**：
#     「语义色层 （ —— 玻璃化的地基）」   ← 中文与括号之间空了一格
#     「追更页玻璃化——进度条换成玻璃件」  ← 破折号两侧没空格
#   ⇒ 统一成：**中文后不留空格接全角括号；破折号两侧各一个空格**。
#   风格跟仓库里的中文注释一致（本文件注释全是 ` —— ` 形态）。
def _normalize_spacing(s: str) -> str:
    # ① 中文 / 右引号 / 右括号 之后接左括号：中间不留空格
    s = re.sub(r"(?<=[\u4e00-\u9fff）」』】》])\s+(?=[（(])", "", s)
    # ② 右括号之后接中文：不留空格（「（玻璃化的地基） 」这种）
    s = re.sub(r"(?<=[)）])\s+(?=[\u4e00-\u9fff])", "", s)
    # ③ 括号内侧不留空格（删标识符留下的）
    s = re.sub(r"(?<=[（(])\s+", "", s)
    s = re.sub(r"\s+(?=[)）])", "", s)
    # ④ 破折号：两侧各一个空格（两个以上的 em dash 也算破折号）
    s = re.sub(r"\s*—{2,}\s*", " —— ", s)
    # ⑤ 尾巴上的「—— 修」是冗余的：这条本来就在 `### 修复` 桶里
    #    实测：「缓存删除徽标对触屏/遥控永远不可见 —— 修 + 粘滞位」
    #          → 删掉「粘滞位」那段后剩「…不可见 —— 修」
    s = re.sub(r"\s*——\s*修\s*$", "", s)
    # ⑤ 全角空格与连续空格归一
    s = s.replace("\u3000", " ")
    s = re.sub(r"\s{2,}", " ", s)
    return s.strip()


def _final_form_ok(s: str) -> bool:
    # ① 以「的/了/是/和/与/或/而/且/并」打头 ⇒ 主语在删除时被带走了
    if s[:1] in "的了是和与或而且并":
        return False
    # ② 括号里只剩空白（删标识符的残留）
    if re.search(r"[（(][\s　]*[)）]", s):
        return False
    if re.search(r"[（(]\s+|\s+[)）]", s):
        return False
    # ③ 工单号/清单残留（即使单位没被 ① 里的正则吃干净）
    if re.search(r"第\s*[一二三四五六七八九十\d]+\s*[步件条轮批处个遍次]", s):
        return False
    if re.search(r"[任轨][务道]\s*[A-Za-z]", s):
        return False
    # ④ 正文里夹着**用户读不懂的英文词**（实现用词，如 glass / Markdown）
    #   ★ 例外表两张：_KEEP_TOKENS 里的（H264 / macOS / 4K…）用户认得；
    #     _MEDIA_FORMAT_TOKENS 里的是**数据格式名**（deflate / m3u8 / hevc…）。
    #     判据边界见上面那张表的 ★★★（"数据的名字"留，"写法的名字"丢）。
    for w in _ASCII_WORD_RE.findall(s):
        if not _ascii_word_allowed(w):
            return False
    # ⑤ 分隔符打头 / 打尾（"—— 玻璃化的地基" 那种只剩半句的）
    if s[:2] in ("——", "--") or s[-2:] == "——":
        return False
    return True


