# ── ① 内部标识：工单号 / 探针名 / 轮次 / 日期工单 ─────────────────────
#
# ★ 这些是**编号**，不是词：删掉对语义毫无损失（对比 ② 的词是句子主干）。
#   所以这里先"剥"，剥完再看句子立不立得住 —— 这是"能删的删"的延续。
#
# ⚠️ 例外表：有些"长得像编号"的串是**用户认识的**（H264 / macOS / 4K），
#    剥掉会让用户彻底读不懂 ⇒ 命中例外表就原样留下。
_KEEP_TOKENS = (
    "H264", "H265", "AV1", "VP9", "MP4", "MKV", "4K", "8K",
    "macOS", "iOS", "iPadOS", "iPhone", "iPad", "iCloud", "YouTube",
)

_TICKET_RE = re.compile(
    r"(?<![A-Za-z0-9_])"
    r"(?:"
    # CS-1 / D-2 / R3-④ / R2-⑥ / N15 / M2 / H1 / P0-10 / N10-VERIFY
    r"(?:CS|R|N|M|D|H|P|E|W|F|B|Z|T|S|L)\d+(?:[-‑][①-⑳\d]+)*(?:-[A-Za-z]+)?"
    # N-PAUSE / N-DEFLATE / LIVE-PROBE / R6-b
    r"|(?:CS|R|N|M|D|H|P|E|W|F|B|Z|T|S|L)-[A-Za-z][A-Za-z0-9]*(?:-v\d+)?"
    r"|[A-Z]{2,}(?:-[A-Za-z0-9]+)+"
    # t74 / t80a / t1015 / t526
    r"|t\d{2,4}[a-z]?"
    # ⑪ / ③⑦ —— 裸圈号
    r"|[①-⑳]+"
    # §3.5
    r"|§\d+(?:\.\d+)*"
    # round-66 / 任务B-3 / 轨道 E / 轨道E
    #   ★ 2026-10-21：`轨道` 与 `E` 之间**允许有空格** —— 实测 rc3 输出里
    #     残留了「轨道 E · settings 第 1 件」，就是空格让旧式漏掉的。
    r"|round-\d+|[任轨][务道]\s*[A-Z]\d*"
    # 第 4 步 / 第一步 / 第 1 件 / 第 2 条 / 第 3 轮
    #   ★ 单位不限于「步」：实测漏过「第 1 件」。
    r"|第\s*[一二三四五六七八九十\d]+\s*[步件条轮批处个遍次]"
    # 2026-10-21（工单日期）
    r"|\d{4}-\d{2}-\d{2}"
    r"|[{★☆}]+"
    r")"
    r"(?![A-Za-z0-9_])"
)

# 文件与符号名
#
# ★ 判据是**形态**而不是清单：本仓任何 `xxx.dart` / `xxx.rs` /
#   `snake_case` / `camelCase` / `SOURIN_*` 都不是用户能感知的东西，
#   而中文用户正文里不会自然出现这些形态 ⇒ 形态本身就是强锚点。
_SYMBOL_RES = (
    # 文件名：live_page.dart / Cargo.toml / .gitattributes
    re.compile(
        r"(?<![\w/])[\w.-]*[\w-]+\.(?:dart|rs|py|ps1|mjs|js|ts|json|ya?ml|toml|"
        r"md|txt|sh|bat|lock|gitattributes)\b"
    ),
    # 全大写下划线（SOURIN_YIELD_PROBE / APP_HOME）
    re.compile(r"(?<![A-Za-z0-9_])[A-Z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)+(?![A-Za-z0-9_])"),
    # 下划线标识符（set_prefetch_disabled / prefetch_disabled / live_page）
    re.compile(r"(?<![A-Za-z0-9_])[A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)+(?![A-Za-z0-9_])"),
    # 前导下划线成员（_exitPlayer）
    re.compile(r"(?<![A-Za-z0-9_])_[A-Za-z][A-Za-z0-9]*(?![A-Za-z0-9_])"),
    # camelCase / PascalCase（AppGlassDialog / showAppToast / WidgetsApp / InkWell）
    re.compile(r"(?<![A-Za-z0-9_])[A-Za-z][a-z0-9]+[A-Z][A-Za-z0-9]*(?![A-Za-z0-9_])"),
    # 短点号符号引用（Sp.x4）
    re.compile(r"(?<![A-Za-z0-9])[A-Z][a-z]?\.[A-Za-z_][A-Za-z0-9_]*"),
)


def _is_keep_token(tok: str) -> bool:
    return tok.strip(" （()）、,，:：").lower() in {t.lower() for t in _KEEP_TOKENS}


def _strip_internal_ids(s: str) -> str:
    """剥掉工单号 / 探针名 / 文件名 / 符号名（保留 _KEEP_TOKENS 里的例外）"""

    def _sub(m: re.Match[str]) -> str:
        return m.group(0) if _is_keep_token(m.group(0)) else ""

    s = _TICKET_RE.sub(_sub, s)
    for rx in _SYMBOL_RES:
        s = rx.sub(_sub, s)

    # 剥完留下的一串连接符 / 空括号 / 括号内多余空白 一律清掉
    s = re.sub(r"[（(]\s*(?:[+＋/／、,，:：\-\s]*)[)）]", "", s)
    # ★ 2026-10-21：**不能**把「触屏/遥控」这种正常斜杠换成空格 ——
    #   实测「缓存删除徽标对触屏 遥控永远不可见」就是这么坏掉的（少了个 /）。
    #   只清「剥掉标识符后」留在段落边界的孤立斜杠。
    s = re.sub(r"(?:^|[—\-－+＋、,，])\s*[/／]+\s*", " ", s)
    # 括号紧贴内容左侧的残留空白：『（ 加可选 glass 档）』⇒『（加可选 glass 档）』
    s = re.sub(r"([（(])\s+", r"\1", s)
    # 括号内以破折号打头：『（ —— 玻璃化的地基）』⇒『（玻璃化的地基）』
    s = re.sub(r"([（(])\s*[—－\-–]{1,2}\s*", r"\1", s)
    # 破折号统一成两侧带空格的『 —— 』（正文里只剩这一种形态）
    #   ★ 2026-10-21：单破折号**两侧都可能带空格**（『玻璃化— 进度条』），
    #     旧式要求两侧都没空格 ⇒ 漏过。这里统一收口，再收拾多余空格。
    s = re.sub(r"\s*—+\s*", " —— ", s)
    # 中文后面紧跟括号时不留空格：『语义色层 （玻璃化的地基）』⇒『语义色层（…）』
    s = re.sub(r"(?<=[\u4e00-\u9fff])\s+([（(])", r"\1", s)
    s = re.sub(r"[ \t]{2,}", " ", s)
